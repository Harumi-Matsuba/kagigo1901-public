"""1901年6月、参謀本部から出した起案2通（C09122814000、C09122815900）の数字のカナ暗号の表（仮に「表C」と呼ぶ）。

表：2桁でカナ1字。十の位＝段（table1901b.py の表と同じ）、一の位＝行。ただし行の番号は逆順で、濁音は後半に分ける。
    前半 01〜49：十の位 0ア段 1イ段 2ウ段 3エ段 4オ段、
                 一の位 9ア 8カ 7サ 6タ 5ナ 4ハ 3マ 2ヤ 1ラ 0ワ
    後半 50〜99：十の位 5ア段 6イ段 7ウ段 8エ段 9オ段、一の位 9ガ 8ザ 7ダ 6バ 5パ
    10＝ン（イ段のワ行の空き）。後半の一の位 0〜4 は使い道が分からない（93 は「十」か）。
規則は、下の ATTESTED の振り仮名・平文から割り出した。ATTESTED の値で規則を作ったので、ATTESTED との一致は規則の確かめではない。
ただし C09122814000 の ゴロ・コウタイ・セシムル は、規則を立ててから当てた値（ラ行＝1 はここで初めて出た）。
使い方: python3 src/table1901c.py
"""
SEI = {9: 'アイウエオ', 8: 'カキクケコ', 7: 'サシスセソ', 6: 'タチツテト', 5: 'ナニヌネノ',
       4: 'ハヒフヘホ', 3: 'マミムメモ', 2: ['ヤ', None, 'ユ', None, 'ヨ'], 1: 'ラリルレロ',
       0: ['ワ', None, None, None, None]}
DAKU = {9: 'ガギグゲゴ', 8: 'ザジズゼゾ', 7: 'ダヂヅデド', 6: 'バビブベボ', 5: 'パピプペポ'}


def table():
    t = {}
    for dan in range(5):
        for unit, row in SEI.items():
            if row[dan]:
                t[dan * 10 + unit] = row[dan]
        for unit, row in DAKU.items():
            t[(dan + 5) * 10 + unit] = row[dan]
    t[10] = 'ン'
    return t


TABLE = table()

# (参照コード, 値, 振り仮名・平文から分かるカナ, 平文の語)。? は振り仮名と表が合わない字。
ATTESTED = [
    ('C09122815900', '28 10 37 18 16 42 29 17', 'クンセキチヨウ?', '勲績調査（17 の振り仮名は サ に見えるが、表では シ）'),
    ('C09122815900', '85 18 10 16 29 58 19', 'ペキンチウザイ', '北京駐在'),
    ('C09122814000', '49 47 28 43', 'オソクモ', '遅クモ'),
    ('C09122814000', '99 41', 'ゴロ', '頃'),
    ('C09122814000', '48 29 06 19', 'コウタイ', '交代'),
    ('C09122814000', '37 17 23 21', 'セシムル', 'セシムル'),
]


def decode(values):
    return ''.join(TABLE.get(int(v), '?') for v in values.split())


if __name__ == '__main__':
    ok = bad = 0
    for ref, v, kana, word in ATTESTED:
        got = decode(v)
        for a, b in zip(got, kana):
            if b != '?':
                ok += a == b
                bad += a != b
        print(ref, v, got, kana, word)
    print('一致', ok, '不一致', bad)
